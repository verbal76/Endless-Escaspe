// Generates docs/THIRD-PARTY-NOTICES.md: the licence and notice text of every
// npm package that is actually inside the shipped JavaScript bundle (derived
// from the Metro source map of a real Android export, not guessed from
// package.json). Native code and assets are covered separately (see the
// file's header and assets/LICENSES.md).
//
// Usage: node scripts/gen-third-party-notices.mjs        (runs `expo export`, ~1 min)
//        node scripts/gen-third-party-notices.mjs --check (fail if the file is stale)
import { execFileSync } from 'node:child_process';
import { existsSync, mkdtempSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

export const OUT = 'docs/THIRD-PARTY-NOTICES.md';
export const PERMISSIVE = new Set(['MIT', 'ISC', 'BSD-2-Clause', 'BSD-3-Clause', 'Apache-2.0', '0BSD', 'Unlicense', 'CC0-1.0']);

/**
 * Packages that contribute at least one module to the bundle, as {name, dir}.
 * `dir` is the package folder relative to the project (nested installs such as
 * node_modules/a/node_modules/b resolve to b, not to a).
 */
export function packagesFromSources(sources) {
  const found = new Map();
  for (const s of sources) {
    const first = s.indexOf('node_modules/');
    const last = s.lastIndexOf('node_modules/');
    if (first < 0) continue;
    const m = s.slice(last + 'node_modules/'.length).match(/^((?:@[^/]+\/)?[^/]+)\//);
    if (!m) continue;
    const dir = s.slice(first, last + 'node_modules/'.length + m[1].length);
    found.set(dir, { name: m[1], dir });
  }
  return [...found.values()].sort((x, y) => x.dir.localeCompare(y.dir));
}

export function licenseText(dir) {
  const f = readdirSync(dir).find((n) => /^(licen[sc]e|copying)(\.(md|txt))?$/i.test(n));
  return f ? readFileSync(join(dir, f), 'utf8').trim() : null;
}

export function describe({ name, dir }) {
  const j = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
  const license = typeof j.license === 'string' ? j.license : JSON.stringify(j.license ?? j.licenses ?? 'UNKNOWN');
  const repo = typeof j.repository === 'string' ? j.repository : j.repository?.url ?? '';
  return { name, version: j.version, license, repo: repo.replace(/^git\+/, '').replace(/\.git$/, ''), text: licenseText(dir) };
}

export function render(pkgs) {
  const bad = pkgs.filter((p) => !PERMISSIVE.has(p.license));
  const out = [
    '# Third-party notices (JavaScript bundle)',
    '',
    `Generated by \`scripts/gen-third-party-notices.mjs\` from the Metro source map of an Android export: the ${pkgs.length} npm packages that contribute code to the shipped bundle,`,
    'with their licence and the licence text found in each package. Regenerate when dependencies change (`node scripts/gen-third-party-notices.mjs`).',
    'Not covered here: native libraries inside the APK (React Native, Hermes, expo modules: see their packages; the Google ML Kit barcode library arrives through',
    '`expo-dev-launcher`, see docs/COMPLIANCE-AUDIT.md finding F-12) and bundled assets (see `assets/LICENSES.md`).',
    '',
    bad.length ? `**Not on the permissive allow-list:** ${bad.map((p) => `${p.name} (${p.license})`).join(', ')}` : 'All listed licences are on the permissive allow-list (MIT, ISC, BSD-2/3-Clause, Apache-2.0, 0BSD, Unlicense, CC0-1.0).',
    '',
    '| Package | Version | Licence |',
    '| --- | --- | --- |',
    ...pkgs.map((p) => `| ${p.name} | ${p.version} | ${p.license} |`),
    '',
  ];
  for (const p of pkgs) {
    out.push(`## ${p.name} ${p.version} (${p.license})`, '', p.repo ? `Source: ${p.repo}` : '', '', p.text ? '```text\n' + p.text.replace(/```/g, "'''") + '\n```' : '_No licence file in the package; licence taken from its package.json._', '');
  }
  return out.join('\n');
}

export function main(argv) {
  const tmp = mkdtempSync(join(tmpdir(), 'notices-'));
  execFileSync('npx', ['expo', 'export', '--platform', 'android', '--dump-sourcemap', '--output-dir', tmp], { stdio: 'ignore', env: { ...process.env, CI: '1', EXPO_NO_TELEMETRY: '1' } });
  const mapDir = join(tmp, '_expo/static/js/android');
  const mapFile = readdirSync(mapDir).find((n) => n.endsWith('.map'));
  const sources = JSON.parse(readFileSync(join(mapDir, mapFile), 'utf8')).sources;
  const md = render(packagesFromSources(sources).map((p) => describe(p)));
  if (argv.includes('--check')) {
    const cur = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
    if (cur !== md) {
      console.error(`${OUT} is stale: run node scripts/gen-third-party-notices.mjs`);
      return 1;
    }
    return 0;
  }
  writeFileSync(OUT, md);
  console.log(`wrote ${OUT}`);
  return 0;
}

if (import.meta.url === `file://${process.argv[1]}`) process.exit(main(process.argv.slice(2)));

// Generates src/ui/iconData.ts: the UI icon PNGs from assets/ui/,
// base64-encoded as data URIs so <Image> shows them straight from the
// JS bundle, with no native asset file to resolve (the same reason the
// textures are embedded - see util/textures.ts).
//
//   node scripts/gen-ui-icons.mjs      (rewrite the module)
//   tests/uiIcons.test.ts              (fails if it is stale)
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

export const UI_ICON_FILES = {
  SETTINGS_GEAR: 'assets/ui/settings-gear.png',
};

export function renderIconModule() {
  const lines = [
    '// Generated by scripts/gen-ui-icons.mjs - do not edit by hand.',
    '// UI icon PNGs from assets/ui/ as data URIs for <Image source={{ uri }}>.',
    '// tests/uiIcons.test.ts keeps it in sync with the files.',
    '',
  ];
  for (const [name, file] of Object.entries(UI_ICON_FILES)) {
    const b64 = readFileSync(path.join(root, file)).toString('base64');
    lines.push(`export const ${name} =`);
    lines.push("  'data:image/png;base64,' +");
    for (let i = 0; i < b64.length; i += 96) {
      const last = i + 96 >= b64.length;
      lines.push(`  '${b64.slice(i, i + 96)}'${last ? ';' : ' +'}`);
    }
    lines.push('');
  }
  return lines.join('\n');
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(path.join(root, 'src/ui/iconData.ts'), renderIconModule());
  console.log('wrote src/ui/iconData.ts');
}

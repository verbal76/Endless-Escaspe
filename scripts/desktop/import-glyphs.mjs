// Imports ONLY the glyph files named in src/desktop/glyphManifest.ts from the studio archive (Source.zip),
// byte for byte, into assets/glyphs/<family>/, writes assets/glyphs/SHA256SUMS and regenerates
// src/desktop/glyphAssets.ts (static require()s, which Metro needs). The original archive is never modified
// and is not stored in the repository.
//
// Usage: node --import ./tests/register.mjs scripts/desktop/import-glyphs.mjs <path-to-Source.zip>
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdirSync, writeFileSync } from 'node:fs';
import { FAMILY_DIRS, GLYPHS } from '../../src/desktop/glyphManifest.ts';

const zip = process.argv[2];
if (!zip) {
  console.error('usage: import-glyphs.mjs <Source.zip>');
  process.exit(2);
}
const sums = [];
const requires = [];
for (const [family, byKey] of Object.entries(GLYPHS)) {
  const { zipDir, dir } = FAMILY_DIRS[family];
  const files = [...new Set(Object.values(byKey).flat())].sort();
  mkdirSync(`assets/glyphs/${dir}`, { recursive: true });
  const entries = [];
  for (const f of files) {
    const bytes = execFileSync('unzip', ['-p', zip, `${zipDir}/${f}`], { maxBuffer: 16 * 1024 * 1024 });
    if (bytes.length < 100 || bytes.subarray(1, 4).toString('latin1') !== 'PNG') throw new Error(`not a PNG: ${zipDir}/${f}`);
    writeFileSync(`assets/glyphs/${dir}/${f}`, bytes);
    sums.push(`${createHash('sha256').update(bytes).digest('hex')}  ${dir}/${f}`);
    entries.push(`    '${f}': require('../../assets/glyphs/${dir}/${f}'),`);
  }
  requires.push(`  ${family}: {\n${entries.join('\n')}\n  },`);
}
writeFileSync('assets/glyphs/SHA256SUMS', sums.join('\n') + '\n');
writeFileSync(
  'src/desktop/glyphAssets.ts',
  `// GENERATED by scripts/desktop/import-glyphs.mjs from the studio glyph archive: do not edit by hand.\n// Imported only by the desktop (web) bundle; the Android bundle never reaches this file.\nimport type { ImageSourcePropType } from 'react-native';\n\nexport const GLYPH_ASSETS: Record<string, Record<string, ImageSourcePropType>> = {\n${requires.join('\n')}\n};\n`,
);
console.log(`imported ${sums.length} glyph files`);

// Generates, from the texture PNGs in assets/:
// - src/util/textureData.ts: each PNG as base64, embedded in the JS
//   bundle so textures load without expo-asset / expo-gl image files
//   (see util/textures.ts);
// - src/util/textureProbes.ts: for every texture, a handful of texel
//   coordinates and the exact RGBA the PNG holds there. The in-app
//   render audit reads the same texels back from the GPU to prove the
//   uploaded texture is really the image (not an empty / black /
//   single-colour texture).
//
//   node scripts/gen-texture-probes.mjs          (rewrite both files)
//   tests/textureProbes.test.ts                  (fails if either is stale)
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { decodePng } from './png-decode.mjs';
export { decodePng };

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

// Must match the keys preloadAllTextures() uses in src/util/textures.ts.
export const TEXTURE_FILES = {
  'character-d': 'assets/characters/texture-d.png',
  'character-g': 'assets/characters/texture-g.png',
  'character-j': 'assets/characters/texture-j.png',
  'vehicle-colormap': 'assets/vehicles/colormap.png',
  'prop-wall': 'assets/props/wall.png',
  'prop-metal_wall': 'assets/props/metal_wall.png',
  'prop-concrete': 'assets/props/concrete.png',
  'prop-signs': 'assets/props/signs.png',
  'prop-roof': 'assets/props/roof.png',
  'prop-grass': 'assets/props/grass.png',
  'prop-dirt': 'assets/props/dirt.png',
};

const MAX_POINTS = 6;

function colorDist(a, b) {
  return Math.abs(a[0] - b[0]) + Math.abs(a[1] - b[1]) + Math.abs(a[2] - b[2]) + Math.abs(a[3] - b[3]);
}

// Greedy: from an 8x8 grid of candidate texels, keep adding the one
// whose colour is farthest from everything picked so far. Distinct
// colours make a wrong / flipped / blank upload easy to detect.
export function probesFor(file) {
  const { width, height, rgba } = decodePng(readFileSync(path.join(root, file)));
  const cands = [];
  for (let gy = 0; gy < 8; gy++) {
    for (let gx = 0; gx < 8; gx++) {
      const x = Math.floor(((gx + 0.5) / 8) * width);
      const y = Math.floor(((gy + 0.5) / 8) * height);
      const i = (y * width + x) * 4;
      cands.push([x, y, rgba[i], rgba[i + 1], rgba[i + 2], rgba[i + 3]]);
    }
  }
  const picked = [cands[0]];
  while (picked.length < MAX_POINTS) {
    let best = null;
    let bestD = -1;
    for (const c of cands) {
      const d = Math.min(...picked.map((p) => colorDist(p.slice(2), c.slice(2))));
      if (d > bestD) {
        bestD = d;
        best = c;
      }
    }
    if (!best || bestD === 0) break;
    picked.push(best);
  }
  return { width, height, points: picked };
}

export function renderProbesModule() {
  const lines = [
    '// Generated by scripts/gen-texture-probes.mjs - do not edit by hand.',
    '// Texel coordinates (x, y from the top-left of the PNG) and the',
    '// RGBA the source image holds there, for the GPU texture check in',
    '// util/renderAudit.ts. tests/textureProbes.test.ts keeps it in sync.',
    '',
    'export type TextureProbe = { width: number; height: number; points: Array<[number, number, number, number, number, number]> };',
    '',
    'export const TEXTURE_PROBES: Record<string, TextureProbe> = {',
  ];
  for (const [key, file] of Object.entries(TEXTURE_FILES)) {
    const p = probesFor(file);
    lines.push(`  '${key}': {`);
    lines.push(`    width: ${p.width},`);
    lines.push(`    height: ${p.height},`);
    lines.push('    points: [');
    for (const pt of p.points) lines.push(`      [${pt.join(', ')}],`);
    lines.push('    ],');
    lines.push('  },');
  }
  lines.push('};', '');
  return lines.join('\n');
}

export function renderDataModule() {
  const lines = [
    '// Generated by scripts/gen-texture-probes.mjs - do not edit by hand.',
    '// The texture PNGs from assets/, base64-encoded, keyed like',
    '// preloadAllTextures() in util/textures.ts. Decoded in JS',
    '// (util/png.ts) and uploaded as raw RGBA. tests/textureProbes.test.ts',
    '// keeps it in sync with the files.',
    '',
    'export const TEXTURE_PNG_BASE64: Record<string, string> = {',
  ];
  for (const [key, file] of Object.entries(TEXTURE_FILES)) {
    const b64 = readFileSync(path.join(root, file)).toString('base64');
    lines.push(`  '${key}':`);
    for (let i = 0; i < b64.length; i += 96) {
      const chunk = b64.slice(i, i + 96);
      const last = i + 96 >= b64.length;
      lines.push(`    '${chunk}'${last ? ',' : ' +'}`);
    }
  }
  lines.push('};', '');
  return lines.join('\n');
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(path.join(root, 'src/util/textureProbes.ts'), renderProbesModule());
  writeFileSync(path.join(root, 'src/util/textureData.ts'), renderDataModule());
  console.log('wrote src/util/textureProbes.ts and src/util/textureData.ts');
}
